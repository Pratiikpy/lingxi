/**
 * Saves the netlist of the first circuit on processor #1 of BNB Chain ("Blonskr_No1", the founder's
 * 4-bit CPU Behemoth) into packages/game, so the game can run it offline. The game checks its copy
 * against the chain when it can.
 *
 *   tsx scripts/fetch-behemoth.ts
 */
import { writeFileSync } from "node:fs";
import { createPublicClient, http, keccak256, parseAbi } from "viem";

const RPC = "https://bsc-dataseed.bnbchain.org";
const PROCESSOR = "0x1F5Cb4aeaE1807Bf60c3b9C0D8aDBCC14e91f12C" as const;
const abi = parseAbi([
  "function netlist(uint256) view returns (bytes)",
  "function circuitInfo(uint256) view returns (uint256,uint256,uint256,uint256)",
  "function name() view returns (string)",
]);
const pub = createPublicClient({ transport: http(RPC) });
const [hex, info, name] = await Promise.all([
  pub.readContract({ address: PROCESSOR, abi, functionName: "netlist", args: [1n] }),
  pub.readContract({ address: PROCESSOR, abi, functionName: "circuitInfo", args: [1n] }),
  pub.readContract({ address: PROCESSOR, abi, functionName: "name" }),
]);
const out = `/** Generated by packages/chain/scripts/fetch-behemoth.ts from BNB Chain. Do not edit. */
export const BEHEMOTH_PROCESSOR = "${PROCESSOR}";
export const BEHEMOTH_PROCESSOR_NAME = ${JSON.stringify(name)};
export const BEHEMOTH_CIRCUIT = 1;
export const BEHEMOTH_PINS = { nIn: ${info[0]}, nOut: ${info[1]}, nState: ${info[2]}, gates: ${info[3]} } as const;
export const BEHEMOTH_NETLIST_KECCAK = "${keccak256(hex)}";
export const BEHEMOTH_NETLIST = "${hex}";
`;
writeFileSync(new URL("../../game/src/behemoth.generated.ts", import.meta.url), out);
console.log(name, info, keccak256(hex));
