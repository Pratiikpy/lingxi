/**
 * A whole trip for the chip's own self-test (firmware `-e selftest`): a pet's packet, a script of keys and time, and
 * the keccak of the packet back that the WebAssembly app (which the game's replay accepts) produces from them. The
 * emulated ESP32-S3 plays the same script and must send back the very same bytes.
 *
 *   npx tsx scripts/build-chip-trip.ts   ->  firmware/cardputer/src/chip_trip.h
 */
import { readFileSync, writeFileSync } from "node:fs";
import { keccak_256 } from "@noble/hashes/sha3";
import { STARTERS, compileProgram, fastBrain, netlistBytes, stateBits } from "@lingxi/brain";
import { BEAT_MS, createPet, newGrowth } from "@lingxi/game";
import { type Snack, bringHome, tripPacket } from "../src/trip";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1");
const T0 = Date.UTC(2026, 10, 17, 2, 0);
const n = compileProgram(STARTERS.curious);
const brain = { fast: fastBrain(n), nState: stateBits(STARTERS.curious) };
const pet = { ...createPet({ name: "Sora", line: "curious", now: T0 - 86_400_000, tzOffsetMin: 330, brain }), beat: Math.floor(T0 / BEAT_MS), growth: newGrowth() };
const snacks: Snack[] = [
  { id: "11110", count: 2, effect: { food: 260, joy: 60, diet: "grain" }, name: { en: "Taro Mochi", zh: "芋泥麻薯" } },
  { id: "11140", count: 1, effect: { food: 180, joy: 90, diet: "sweet" }, name: { en: "Honey Mochi", zh: "蜂蜜麻薯" } },
];
const packet = tripPacket(pet, { processor: "0xf70d324da8c1c4cb0de3ff147e53e7e9db543c4e", id: 1n, bytes: netlistBytes(n), parts: [] }, snacks, {
  name: "Sora",
  line: "curious",
  stage: 2,
  form: 0,
  colour: 0,
  lang: "en",
  bornBeat: Math.floor((T0 - 86_400_000) / BEAT_MS),
});

/** the script: [ms, beat offset, present, key or 0] */
const B = pet.beat;
const script: Array<[number, number, number, number]> = [
  [1000, 1, 1, 0],
  [1100, 1, 1, "f".charCodeAt(0)],
  [1200, 1, 1, "1".charCodeAt(0)],
  [1300, 1, 1, "h".charCodeAt(0)],
  [2000, 2, 1, "c".charCodeAt(0)],
  [60_000, 42, 0, 0],
  [60_100, 43, 1, "t".charCodeAt(0)],
  [60_200, 43, 1, "f".charCodeAt(0)],
  [60_300, 43, 1, "2".charCodeAt(0)],
  [61_000, 44, 1, "m".charCodeAt(0)],
  [62_000, 47, 1, "l".charCodeAt(0)],
  [63_000, 50, 1, "l".charCodeAt(0)],
  [64_000, 51, 1, 0],
];

const { instance } = await WebAssembly.instantiate(readFileSync(`${root}/wasm/lingxi-handheld.wasm`), {});
const x = instance.exports as Record<string, (...a: number[]) => number> & { memory: WebAssembly.Memory };
x.hh_init!(0);
new Uint8Array(x.memory.buffer).set(packet, x.hh_in!());
if (x.hh_open!(packet.length) !== 0) throw new Error("the packet did not open");
for (const [ms, beat, present, key] of script) {
  x.hh_tick!(ms, B + beat, present);
  if (key) x.hh_key!(key);
}
const len = x.hh_close!();
const back = new Uint8Array(x.memory.buffer, x.hh_out!(), len).slice();
const home = bringHome(pet, brain, snacks, back, (B + 52) * BEAT_MS);
if (!home.ok) throw new Error(`the game refused the trip: ${home.reason}`);

const hex = (b: Uint8Array) => Array.from(b, (v) => `0x${v.toString(16).padStart(2, "0")}`);
const rows = (b: Uint8Array) => hex(b).reduce<string[]>((acc, v, i) => (i % 16 ? (acc[acc.length - 1] += `, ${v}`) : acc.push(`  ${v}`), acc), []).join(",\n");
const header = `/* generated by scripts/build-chip-trip.ts; do not edit. A trip the WebAssembly app plays and the game accepts. */
#pragma once
#include <stdint.h>

static const uint8_t CHIP_TRIP_PACKET[${packet.length}] = {
${rows(packet)}
};
static const uint32_t CHIP_TRIP_PACKET_LEN = ${packet.length};
static const int32_t CHIP_TRIP_BEAT = ${B};
/* ms, beats after the pet's own, present, key (0 for none) */
static const int32_t CHIP_TRIP_SCRIPT[][4] = {
${script.map((s) => `  {${s.join(", ")}}`).join(",\n")}
};
static const uint32_t CHIP_TRIP_STEPS = ${script.length};
static const uint32_t CHIP_TRIP_BACK_LEN = ${back.length};
/* keccak-256 of the packet back */
static const uint8_t CHIP_TRIP_BACK_KECCAK[32] = { ${hex(keccak_256(back)).join(", ")} };
`;
writeFileSync(`${root}/firmware/cardputer/src/chip_trip.h`, header);
console.log(`chip trip: packet ${packet.length} bytes, ${script.length} steps, packet back ${back.length} bytes, game replay ok (${home.cares.length} cares)`);
