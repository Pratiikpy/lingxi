/**
 * What the handheld checks at boot, written to core/selftest_data.c:
 *   - the three starter brains' netlists, and the keccak-256 of each as stored on X Layer (the README's proof table,
 *     which `pnpm judge:check` re-reads from the chain): the handheld hashes its copies and compares;
 *   - pet #1's saved mainnet log (33 words) and what replaying it through the gentle brain must give: the log hash
 *     PetRegistry holds for that checkpoint and the brain's memory after it.
 * The script refuses to write if the netlists compiled here do not hash to the chain's values.
 *
 *   npx tsx scripts/build-selftest.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { keccak_256 } from "@noble/hashes/sha3";
import { STARTERS, compileProgram, fastBrain, netlistBytes } from "@lingxi/brain";
import { ZERO_HASH, chainAll } from "@lingxi/game";
import { RECORDED_STARTERS } from "../src/recorded";

// keccak-256 of each starter's netlist on X Layer, shared with the browser handheld that confirms them live (A59)
const ON_CHAIN = RECORDED_STARTERS;

const hex = (b: Uint8Array) => `0x${Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("")}`;
const bytesOf = (h: string) => Array.from({ length: (h.length - 2) / 2 }, (_, i) => parseInt(h.slice(2 + 2 * i, 4 + 2 * i), 16));
const c = (xs: number[]) => xs.join(", ");

const lines: string[] = ["/* Generated by scripts/build-selftest.ts. Do not edit. */", '#include "selftest.h"', ""];
const order = ["gentle", "bold", "curious"] as const;
for (const [i, line] of order.entries()) {
  const n = compileProgram(STARTERS[line]);
  const bytes = netlistBytes(n);
  const h = hex(keccak_256(bytes));
  if (h !== ON_CHAIN[line]) throw new Error(`${line}: compiled ${h}, X Layer holds ${ON_CHAIN[line]}`);
  lines.push(`static const uint8_t starter${i}[] = {${c(Array.from(bytes))}};`);
  lines.push(`static const uint8_t starter${i}_hash[32] = {${c(bytesOf(ON_CHAIN[line]))}};`);
}
lines.push("const lx_starter lx_starters[3] = {");
for (const [i, line] of order.entries()) {
  const n = compileProgram(STARTERS[line]);
  lines.push(`  {"${line}", ${i + 1}, starter${i}, sizeof starter${i}, starter${i}_hash, ${n.latches.length}},`);
}
lines.push("};");

const log = JSON.parse(readFileSync(new URL("../../chain/deployments/pet-1-log.json", import.meta.url), "utf8")) as { segments: Array<{ brainId: string; words: number[] }> };
if (log.segments.some((s) => s.brainId !== "1")) throw new Error("pet #1's log is expected to run on the gentle brain throughout");
const words = log.segments.flatMap((s) => s.words);
const gentle = compileProgram(STARTERS.gentle);
const fast = fastBrain(gentle);
const st = new Uint8Array(gentle.latches.length);
for (const w of words) fast.step(st, w);
lines.push(`const uint16_t lx_pet1_words[${words.length}] = {${c(words)}};`);
lines.push(`const uint32_t lx_pet1_count = ${words.length};`);
lines.push(`const uint8_t lx_pet1_hash[32] = {${c(bytesOf(chainAll(ZERO_HASH, words)))}};`);
lines.push(`const uint8_t lx_pet1_memory[${st.length}] = {${c(Array.from(st))}};`);
lines.push("");
writeFileSync(new URL("../core/selftest_data.c", import.meta.url), lines.join("\n"));
process.stdout.write(`self-test: 3 starters match X Layer; pet #1: ${words.length} words, log hash ${chainAll(ZERO_HASH, words).slice(0, 18)}…\n`);
