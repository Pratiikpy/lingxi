/**
 * The handheld's pictures, cut from the game's own art exactly as PetLook stores them on X Layer (packages/chain
 * look.ts `buildLayers`): run-length layers (x, y, length, colour role), each slot's face anchors and frame, and the
 * palettes, written to core/art_data.c. Also the colours the handheld shares with the game: each behaviour's colour
 * and the name colours on their dark backgrounds.
 *
 *   npx tsx scripts/build-art.ts
 */
import { writeFileSync } from "node:fs";
import { EXPRESSIONS, ROLES, type Role } from "@lingxi/art";
import { buildLayers, lookPalettes } from "@lingxi/chain";
import { NAME_COLOURS } from "@lingxi/world";

const WANT_COLORS = ["#D9D1E6", "#FFB38A", "#FFD45E", "#A9BEF2", "#9BDDA6", "#C9A6DD", "#FFB3C7", "#8ED8D2"];

const rgb565 = (hex: string): number => {
  const h = hex.replace("#", "");
  const r = parseInt(h.slice(0, 2), 16), g = parseInt(h.slice(2, 4), 16), b = parseInt(h.slice(4, 6), 16);
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
};
const palette = (p: Partial<Record<Role, string>>): number[] => ROLES.map((r, i) => (i === 0 || !p[r] ? 0 : rgb565(p[r]!)));
const opaque = (p: Partial<Record<Role, string>>): number => ROLES.reduce((m, r, i) => (i > 0 && p[r] && (p[r]!.length === 7 || p[r]!.endsWith("ff")) ? m | (1 << i) : m), 0);

const built = buildLayers();
const pals = lookPalettes();
const runs: number[] = [];
const layers = built.layers.map((l) => {
  const at = runs.length / 4;
  const b = l.data.slice(2).match(/../g)!.map((h) => parseInt(h, 16));
  runs.push(...b);
  return { key: l.key, at, n: b.length / 4 };
});

const lines: string[] = [];
const w = (s: string) => lines.push(s);
const list = (xs: number[], per = 16) => {
  for (let i = 0; i < xs.length; i += per) w("  " + xs.slice(i, i + per).join(", ") + ",");
};
w("/* Generated by scripts/build-art.ts from the game's art as PetLook stores it on X Layer. Do not edit. */");
w('#include "art.h"');
w("");
w(`const uint32_t lx_layer_count = ${layers.length};`);
w("const lx_layer lx_layers[] = {");
for (const l of layers) w(`  {${l.key}, ${l.at}, ${l.n}},`);
w("};");
w("const uint8_t lx_layer_runs[] = {");
list(runs, 32);
w("};");
w(`const uint32_t lx_anchor_count = ${built.anchors.length};`);
w("const lx_anchor lx_anchors[] = {");
for (const a of built.anchors) w(`  {${a.slot}, ${a.large ? 1 : 0}, {${a.at.map(([x, y]) => `{${x}, ${y}}`).join(", ")}}},`);
w("};");
w(`const uint32_t lx_frame_count = ${built.frames.length};`);
w("const lx_frame_box lx_frames[] = {");
for (const f of built.frames) w(`  {${f.slot}, ${f.x}, ${f.y}, ${f.size}},`);
w("};");
w("const uint16_t lx_pet_palettes[3][17] = {");
for (const p of pals.pets) w(`  {${palette(p).join(", ")}},`);
w("};");
w("const uint16_t lx_egg_palettes[3][17] = {");
for (const p of pals.eggs) w(`  {${palette(p).join(", ")}},`);
w("};");
w(`const uint32_t lx_pet_opaque[3] = {${pals.pets.map(opaque).join(", ")}};`);
w(`/* faces, in the order of packages/art EXPRESSIONS: ${EXPRESSIONS.join(", ")} */`);
w(`const uint16_t lx_want_colours[8] = {${WANT_COLORS.map(rgb565).join(", ")}};`);
w(`/* name colours 1..8 as the game draws them on a dark background */`);
w(`const uint16_t lx_name_colours[9] = {0, ${NAME_COLOURS.map((c) => rgb565(c.dark)).join(", ")}};`);
w("");
writeFileSync(new URL("../core/art_data.c", import.meta.url), lines.join("\n"));

const exprIndex = Object.fromEntries(EXPRESSIONS.map((e, i) => [e, i]));
const h = [
  "/* Generated by scripts/build-art.ts. Do not edit. */",
  "#ifndef LX_ART_H",
  "#define LX_ART_H",
  "#include <stdint.h>",
  "",
  "typedef struct { uint16_t key; uint32_t at, n; } lx_layer;",
  "typedef struct { uint8_t slot, large; int8_t at[16][2]; } lx_anchor;",
  "typedef struct { uint8_t slot, x, y, size; } lx_frame_box;",
  "",
  "extern const uint32_t lx_layer_count, lx_anchor_count, lx_frame_count;",
  "extern const lx_layer lx_layers[];",
  "extern const uint8_t lx_layer_runs[];",
  "extern const lx_anchor lx_anchors[];",
  "extern const lx_frame_box lx_frames[];",
  "extern const uint16_t lx_pet_palettes[3][17], lx_egg_palettes[3][17];",
  "extern const uint32_t lx_pet_opaque[3];",
  "extern const uint16_t lx_want_colours[8], lx_name_colours[9];",
  "",
  "/* faces, by packages/art EXPRESSIONS */",
  ...EXPRESSIONS.map((e) => `#define LX_FACE_${e.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()} ${exprIndex[e]}`),
  "",
  "#endif",
  "",
];
writeFileSync(new URL("../core/art.h", import.meta.url), h.join("\n"));
process.stdout.write(`art: ${layers.length} layers, ${runs.length / 4} runs, ${built.anchors.length} anchors, ${built.frames.length} frames\n`);
