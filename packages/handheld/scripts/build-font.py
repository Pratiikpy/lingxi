"""Cut the handheld's font from Fusion Pixel Font 12px (zh_hans, BDF; glyphs under the SIL Open Font License 1.1, see
assets/fonts/): ASCII and Latin-1, punctuation, arrows and symbols, CJK punctuation, full-width forms and all 6,763
hanzi of GB2312, so a pet's Chinese name draws too. Writes core/font_data.c: a sorted code-point table and, per glyph,
its advance, box and rows of bits (most significant bit leftmost).

    python -I scripts/build-font.py <path to fusion-pixel-12px-proportional-zh_hans.bdf>
"""
import os
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x205E), (0x2190, 0x21FF), (0x2460, 0x24FF), (0x2500, 0x259F),
          (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF), (0x3000, 0x303F), (0xFF00, 0xFFEF)]


def gb2312():
    out = []
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                out.append(ord(bytes([hi, lo]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    return out


def read_bdf(path):
    glyphs = {}
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    i = 0
    ascent = descent = None
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("FONT_ASCENT"):
            ascent = int(ln.split()[1])
        elif ln.startswith("FONT_DESCENT"):
            descent = int(ln.split()[1])
        elif ln.startswith("STARTCHAR"):
            cp = adv = None
            bbx = None
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                t = lines[i]
                if t.startswith("ENCODING"):
                    cp = int(t.split()[1])
                elif t.startswith("DWIDTH"):
                    adv = int(t.split()[1])
                elif t.startswith("BBX"):
                    bbx = tuple(int(x) for x in t.split()[1:5])
                elif t == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    break
                i += 1
            if cp is not None and cp >= 0 and bbx:
                glyphs[cp] = (adv, bbx, rows)
        i += 1
    return glyphs, ascent, descent


def main():
    src = sys.argv[1]
    glyphs, ascent, descent = read_bdf(src)
    want = set()
    for a, b in RANGES:
        want.update(range(a, b + 1))
    want.update(gb2312())
    cps = sorted(c for c in want if c in glyphs)
    pool = bytearray()
    recs = []
    for cp in cps:
        adv, (w, h, xo, yo), rows = glyphs[cp]
        bpr = (w + 7) // 8
        at = len(pool)
        for r in rows[:h]:
            v = int(r, 16) if r else 0
            nbytes = len(r) // 2
            for k in range(bpr):
                shift = 8 * (nbytes - 1 - k)
                pool.append((v >> shift) & 0xFF if shift >= 0 else 0)
        recs.append((cp, adv, w, h, xo, yo, at))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "core", "font_data.c")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by scripts/build-font.py from Fusion Pixel Font 12px (SIL OFL 1.1, assets/fonts). Do not edit. */\n")
        f.write('#include "draw.h"\n\n')
        f.write(f"const int lx_font_ascent = {ascent};\nconst int lx_font_descent = {descent};\nconst uint32_t lx_font_count = {len(cps)};\n")
        f.write("const uint32_t lx_font_cp[] = {\n")
        for i in range(0, len(recs), 12):
            f.write("  " + ", ".join(str(r[0]) for r in recs[i:i + 12]) + ",\n")
        f.write("};\nconst lx_glyph lx_font_glyph[] = {\n")
        for r in recs:
            f.write(f"  {{{r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]}, {r[6]}}},\n")
        f.write("};\nconst uint8_t lx_font_bits[] = {\n")
        for i in range(0, len(pool), 24):
            f.write("  " + ",".join(str(b) for b in pool[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"{len(cps)} glyphs, {len(pool)} bitmap bytes -> core/font_data.c (ascent {ascent}, descent {descent})")


main()
