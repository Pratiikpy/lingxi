/**
 * A pet's brain as Verilog (PRD F9), from the same netlist that is taped out:
 * one NAND per gate, one register per memory latch. Two modules:
 *
 *   <name>_step  combinational: the 16 input pins and the memory in, the 8
 *                output pins and the next memory out (one beat of thought)
 *   <name>       the pet: the step with its memory held in registers, one beat
 *                per rising clock edge, cleared by reset
 *
 * Signal numbering follows TAP-02 as our compiler emits it: 0 and 1 are the
 * constants, then the input pins, then the latch outputs, then the gates in
 * order; the last 8 gates are the outputs.
 */

import type { PetNetlist } from "./compile";

const ident = (s: string) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(s) ? s : "lingxi_brain");

export function toVerilog(n: PetNetlist, name = "lingxi_brain"): string {
  const mod = ident(name);
  const latchBase = 2 + n.nIn;
  const gateBase = latchBase + n.latches.length;
  const S = n.latches.length;
  const sig = (i: number): string => {
    if (i === 0) return "1'b0";
    if (i === 1) return "1'b1";
    if (i < latchBase) return `pins[${i - 2}]`;
    if (i < gateBase) return `mem[${i - latchBase}]`;
    return `g${i - gateBase}`;
  };
  const lines: string[] = [];
  lines.push(`// ${mod}: ${n.gates.length} NAND gates, ${S} memory latches, ${n.nIn} inputs, ${n.nOut} outputs.`);
  lines.push(`// Generated by Lingxi from the same netlist that is taped out on X Layer (TAP-02).`);
  lines.push("");
  lines.push(`module ${mod}_step (`);
  lines.push(`  input  wire [${n.nIn - 1}:0] pins,`);
  if (S > 0) lines.push(`  input  wire [${S - 1}:0] mem,`);
  if (S > 0) lines.push(`  output wire [${S - 1}:0] next,`);
  lines.push(`  output wire [${n.nOut - 1}:0] out`);
  lines.push(`);`);
  n.gates.forEach(([a, b], i) => lines.push(`  wire g${i} = ~(${sig(a)} & ${sig(b)});`));
  n.latches.forEach((d, j) => lines.push(`  assign next[${j}] = ${sig(d)};`));
  const first = n.gates.length - n.nOut;
  for (let k = 0; k < n.nOut; k++) lines.push(`  assign out[${k}] = g${first + k};`);
  lines.push(`endmodule`);
  lines.push("");
  lines.push(`module ${mod} (`);
  lines.push(`  input  wire clk,`);
  lines.push(`  input  wire reset,`);
  lines.push(`  input  wire [${n.nIn - 1}:0] pins,`);
  lines.push(`  output wire [${n.nOut - 1}:0] out`);
  lines.push(`);`);
  if (S > 0) {
    lines.push(`  reg  [${S - 1}:0] mem;`);
    lines.push(`  wire [${S - 1}:0] next;`);
    lines.push(`  ${mod}_step step (.pins(pins), .mem(mem), .next(next), .out(out));`);
    lines.push(`  always @(posedge clk) mem <= reset ? ${S}'b0 : next;`);
  } else {
    lines.push(`  ${mod}_step step (.pins(pins), .out(out));`);
  }
  lines.push(`endmodule`);
  return lines.join("\n") + "\n";
}
