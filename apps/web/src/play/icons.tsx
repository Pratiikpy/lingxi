export type IconName = keyof typeof GRID;

export function Icon({ name, size = 24, title }: { name: IconName; size?: number; title?: string }) {
  const rows = GRID[name]!;
  const rects: string[] = [];
  rows.forEach((r, y) => {
    let x = 0;
    while (x < r.length) {
      if (r[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (r[x + w] === "#") w++;
      rects.push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w;
    }
  });
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      aria-label={title}
      style={{ flex: "none" }}
    >
      <path d={rects.join("")} fill="currentColor" />
    </svg>
  );
}
